type I18n = { language: Language; setLanguage: (language: Language) => void; t: (english: string) => string };
const LanguageContext = createContext<I18n | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try { return localStorage.getItem(languageStorageKey) === 'zh' ? 'zh' : 'en'; }
    catch { return 'en'; }
  });
  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    try { localStorage.setItem(languageStorageKey, language); } catch { /* Language switching still works without storage. */ }
  }, [language]);
  const t = useCallback((english: string) => language === 'zh' ? (chinese[english] ?? english) : english, [language]);
  const value = useMemo(() => ({ language, setLanguage, t }), [language, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useI18n must be used inside LanguageProvider');
  return context;
}

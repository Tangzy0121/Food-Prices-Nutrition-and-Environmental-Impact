const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const path = require('node:path');
const { mkdir } = require('node:fs/promises');
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true});
  try {
    const screenshots=path.resolve(__dirname,'../../.scratch/consumer-check');
    await mkdir(screenshots,{recursive:true});
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[]; page.on('pageerror', e=>errors.push(e.message));
    await page.goto(process.argv[2] || 'http://127.0.0.1:5173/#dashboard');
    await page.getByRole('button',{name:'中文',exact:true}).click();
    await page.getByRole('tab').first().waitFor();
    assert.equal(await page.getByRole('tab').count(),3,'Only nutrition, environment and joint tabs');
    assert.equal(await page.locator('option[value="all"]').count(),0);
    await page.getByRole('tab',{name:'01 营养',exact:true}).click();
    assert.equal(await page.locator('[data-chart="nutrients"] [data-point]').count(),590);
    await page.getByRole('checkbox',{name:'纤维',exact:true}).check();
    assert.equal(await page.locator('[data-chart="nutrients"] [data-point]').count(),1111);
    await page.getByRole('checkbox',{name:'糖',exact:true}).uncheck();
    await page.getByRole('checkbox',{name:'纤维',exact:true}).uncheck();
    await page.getByText('请选择至少一种营养成分。',{exact:true}).waitFor();
    await page.getByRole('checkbox',{name:'糖',exact:true}).check();
    const axesBefore = await page.locator('[data-chart="nutrients"] text').allTextContents();
    await page.getByRole('checkbox',{name:'饼干',exact:true}).uncheck();
    assert.equal(await page.locator('[data-chart="nutrients"] [data-category="biscuits"]').count(),0);
    assert.deepEqual(await page.locator('[data-chart="nutrients"] text').allTextContents(),axesBefore,'Toggling a category must preserve the axes');
    await page.screenshot({path:path.join(screenshots,'nutrition.png'),fullPage:true});
    await page.getByRole('tab',{name:'02 环境',exact:true}).click();
    assert.equal(await page.locator('[data-chart="carbon"]').count(),1);
    await page.screenshot({path:path.join(screenshots,'environment.png'),fullPage:true});
    await page.getByRole('tab',{name:'03 联合比较',exact:true}).click();
    await page.getByRole('checkbox',{name:'饼干',exact:true}).check();
    assert.equal(await page.locator('[data-chart="joint"] [data-point]').count(),583);
    await page.locator('[data-chart="joint"] [data-point]').last().click();
    await page.locator('.selected-product').waitFor();
    await page.getByRole('button',{name:'关闭商品详情',exact:true}).click();
    await page.screenshot({path:path.join(screenshots,'joint.png'),fullPage:true});
    await page.locator('[data-chart="joint"] [data-point]').first().focus();
    await page.keyboard.press('Enter');
    await page.locator('.selected-product').waitFor();
    for(const name of ['饼干','早餐谷物','黑巧克力','果汁']) await page.getByRole('checkbox',{name,exact:true}).uncheck();
    await page.getByText('请选择至少一类食品。',{exact:true}).waitFor();
    await page.getByRole('button',{name:'显示全部',exact:true}).click();
    assert.equal(await page.locator('[data-chart="joint"] [data-point]').count(),583);
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),'No page overflow on mobile');
    await page.screenshot({path:path.join(screenshots,'mobile.png'),fullPage:true});
    await page.getByRole('link',{name:'故事',exact:true}).click();
    assert.equal(await page.locator('.chapter-rail a').count(),8,'Eight narrative chapters');
    assert.equal(await page.getByRole('heading',{level:1}).first().textContent().then(t=>t.includes('更好的食物')),true,'Story opening renders in Chinese');
    await page.getByRole('link',{name:'01 问题',exact:false}).click();
    await page.getByText('没有一个叫“值不值”。',{exact:false}).waitFor();
    await page.getByRole('link',{name:'07 结论',exact:false}).click();
    await page.getByText('价格是一个很弱的标签。',{exact:false}).first().waitFor();
    await page.getByRole('link',{name:'数据来源与处理流程',exact:true}).first().click();
    assert.equal(await page.locator('.resource-list>a').count(),2);
    assert.equal(await page.locator('.consumer-processing li').count(),5);
    await page.getByRole('link',{name:'仪表板',exact:true}).click();
    await page.getByRole('button',{name:'English',exact:true}).click();
    await page.getByRole('tab',{name:'03 Joint comparison',exact:true}).click();
    assert.deepEqual(errors,[]);
    console.log('PASS: three tabs, combined charts, nutrient/category toggles, empty selections, joint detail, bilingual and mobile.');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
